// Attach Clerk session tokens to same-origin API requests. Firebase is used only
// by the server-side Admin SDK for Firestore; no Firebase Auth runs in browser.
if (!window.__clerkApiFetchInstalled && typeof window.fetch === "function") {
  const nativeFetch = window.fetch.bind(window);
  window.fetch = async (input, init = {}) => {
    const requestUrl = input instanceof Request ? input.url : String(input);
    let parsedUrl;
    try { parsedUrl = new URL(requestUrl, window.location.href); } catch (_) {}
    if (parsedUrl?.origin === window.location.origin && parsedUrl.pathname.startsWith("/api/")) {
      const headers = new Headers(input instanceof Request ? input.headers : undefined);
      new Headers(init.headers || {}).forEach((value, key) => headers.set(key, value));
      if (!headers.has("Authorization")) {
        const token = window.Clerk?.session ? await window.Clerk.session.getToken() : "";
        if (token) headers.set("Authorization", `Bearer ${token}`);
      }
      return nativeFetch(input, { ...init, headers });
    }
    return nativeFetch(input, init);
  };
  window.__clerkApiFetchInstalled = true;
}

function getAutoGeneratedPFP(seed) {
  const cleanSeed = encodeURIComponent(String(seed || "gtm-operator").trim().toLowerCase());
  return `https://api.dicebear.com/9.x/bottts/svg?seed=${cleanSeed}&backgroundColor=6366f1,8b5cf6,3b82f6,0ea5e9,10b981`;
}
window.getAutoGeneratedPFP = getAutoGeneratedPFP;

function updateSidebarUserAvatar(displayName, email) {
  const avatarEl = document.getElementById("sidebar-user-avatar");
  if (!avatarEl) return;
  const seed = email || displayName || "gtm-operator";
  const pfpUrl = getAutoGeneratedPFP(seed);
  avatarEl.innerHTML = `<img src="${pfpUrl}" alt="${displayName || 'User'}" style="width:100%;height:100%;border-radius:50%;object-fit:cover;display:block;" onerror="this.onerror=null;this.parentElement.innerHTML='<span id=\\'clerk-user-initials\\'>${(displayName || email || 'GO').slice(0, 2).toUpperCase()}</span>'">`;
  avatarEl.setAttribute("title", `${displayName || 'User'} (${email || ''})`);
}
window.updateSidebarUserAvatar = updateSidebarUserAvatar;
